import Ajv from "ajv";
import standalone from "ajv/dist/standalone/index.js";
import {writeFile} from "node:fs/promises";
import {exchangeSchema} from "../../studio/exchange/schema.ts";
const ajv=new Ajv({allErrors:true,ownProperties:true,strict:true,code:{source:true,esm:true}});
const code=standalone(ajv,ajv.compile(exchangeSchema)).replace(/const (\w+) = require\("([^"]+)"\)\.default;/g,'import * as $1Module from "$2.js"; const $1 = $1Module.default?.default ?? $1Module.default;');
if(code.includes("require("))throw Error("Unbekannte Validatorabhängigkeit");
await writeFile("studio/exchange/validate.generated.js","// Generated by scripts/studio/generate-exchange-validator.mjs\n"+code+"\n");
