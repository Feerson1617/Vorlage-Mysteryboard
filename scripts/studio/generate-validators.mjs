import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFile, writeFile } from "node:fs/promises";
const content = JSON.parse(
  await readFile("schemas/mystery-content.schema.json"),
);
const document = JSON.parse(
  await readFile("schemas/mystery-document.schema.json"),
);
const draft = structuredClone(content);
draft.$id = "MysteryBoardDraftContent";
draft.properties.cards.minItems = 0;
draft.properties.title.minLength = 0;
const ajv = new Ajv({
  allErrors: false,
  strict: true,
  code: { source: true, esm: true },
});
ajv.addSchema(content).addSchema(draft).addSchema(document);
let code = standaloneCode(ajv, {
  checkContent: content.$id,
  checkDraftContent: draft.$id,
  checkDocument: document.$id,
});
code = code.replace(
  /const (\w+) = require\("([^"]+)"\)\.default;/g,
  'import * as $1Module from "$2.js"; const $1 = $1Module.default?.default ?? $1Module.default;',
);
if (code.includes("require(")) throw Error("Unexpected validator dependency");
await writeFile(
  "src/core/document-validators.generated.js",
  "// Generated by scripts/studio/generate-validators.mjs from the project schemas.\n" +
    code +
    "\n",
);
await writeFile(
  "src/core/document-validators.generated.d.ts",
  'import type {ValidateFunction} from "ajv";\nexport const checkContent:ValidateFunction;\nexport const checkDraftContent:ValidateFunction;\nexport const checkDocument:ValidateFunction;\n',
);
